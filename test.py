def parse_link_text(link_text):
    """Парсит ссылки, включая книги с цифрами (1Ин, 2Ин, 1Пет и т.д.)"""
    links = []
    # ИСПРАВЛЕНО: теперь захватывает цифры в названии книги
    parts = re.split(r'[;,]\s*', link_text)
    
    for part in parts:
        part = part.strip()
        if not part:
            continue
        
        # Паттерн: (цифра?)(название книги) пробел глава:стих(ы)
        match = re.match(r'(\d?)([А-Я][а-я]+)\s+(\d+):(\d+(?:-\d+)?)', part)
        if match:
            digit = match.group(1)
            book_name = match.group(2)
            if digit:
                book_name = digit + book_name
            chapter_num = int(match.group(3))
            verse_str = match.group(4)
            
            if '-' in verse_str:
                parts_range = verse_str.split('-')
                try:
                    start = int(parts_range[0])
                    end = int(parts_range[1])
                    for v in range(start, end + 1):
                        link_ref = f"{book_name} {chapter_num}:{v}"
                        if link_ref not in links:
                            links.append(link_ref)
                except ValueError:
                    pass
            else:
                try:
                    verse_num = int(verse_str)
                    link_ref = f"{book_name} {chapter_num}:{verse_num}"
                    if link_ref not in links:
                        links.append(link_ref)
                except ValueError:
                    pass
    
    return links

